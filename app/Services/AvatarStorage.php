<?php
namespace App\Services;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;
use Illuminate\Validation\ValidationException;
use Intervention\Image\Drivers\Gd\Driver;
use Intervention\Image\Exceptions\DecoderException;
use Intervention\Image\ImageManager;
use RuntimeException;
class AvatarStorage
{
    public function store(UploadedFile $file): string
    {
        try {
            // Re-encode decoded pixels; never publish the original upload bytes.
            $manager = new ImageManager(new Driver(), decodeAnimation: false);
            $jpeg = $manager->read($file->getRealPath())
                ->cover(256, 256)
                ->toJpeg(quality: 85, strip: true);
        } catch (DecoderException $exception) {
            throw ValidationException::withMessages([
                'avatar' => 'The image could not be decoded. Choose a different JPEG, PNG, or WebP file.',
            ]);
        }
        $path = 'avatars/'.Str::uuid().'.jpg';
        if (! Storage::disk('public')->put($path, (string) $jpeg)) {
            throw new RuntimeException('The prepared avatar could not be stored.');
        }
        return $path;
    }
    public function delete(?string $path): void
    {
        // Delete only files generated by this service, never submitted filenames.
        if ($path && preg_match('/\Aavatars\/[0-9a-f-]{36}\.jpg\z/i', $path)) {
            Storage::disk('public')->delete($path);
        }
    }
}
